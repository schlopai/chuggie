def write_example(subdir, level, name):
    ex = os.path.join(REPO, "examples", subdir)
    os.makedirs(os.path.join(ex, "assets"), exist_ok=True)
    os.makedirs(os.path.join(ex, "src"), exist_ok=True)
    make_tileset().save(os.path.join(ex, "assets", "tileset.png"))
    make_hero().save(os.path.join(ex, "assets", "hero.png"))
    w, h, data, spawn = parse_level(level)
    emit_maps_tish(os.path.join(ex, "src", "maps.tish"), name, w, h, data, spawn)
    print(f"{subdir}: {w}x{h} tiles, spawn {spawn}")


